def flow(anchors, months=MONTHS):
    """Ряд по месяцам: линейно между опорами, ноль до первой, уровень после последней."""
    pts = sorted(anchors.items())
    out = [0.0] * (months + 1)
    for (m0, v0), (m1, v1) in zip(pts, pts[1:]):
        for m in range(m0, m1 + 1):
            out[m] = v0 + (v1 - v0) * (m - m0) / (m1 - m0)
    last_m, last_v = pts[-1]
    for m in range(last_m, months + 1):
        out[m] = last_v
    return out


def xround(x):
    """Округление до целого как у ROUND в Excel: половина — вверх. У Python round() иначе."""
    return float(math.floor(x + 0.5))


def whole(xs):
    """Штуки — только целые: компания, сделка, подписчик, ставка."""
    return [xround(x) for x in xs]


def stock(adds, churn):
    """База: прошлый месяц минус ушедшие плюс новые. Ушедших — целое число.

    Так же считает книга: =прошлый-ROUND(прошлый*отток;0)+новые.
    """
    out = [0.0] * len(adds)
    for m in range(1, len(adds)):
        out[m] = out[m - 1] - xround(out[m - 1] * churn) + adds[m]
    return out


def solve(f, target, lo=0.0, hi=1e8):
    """Наименьшее значение, при котором f(значение) достигает цели. f растёт."""
    for _ in range(200):
        mid = (lo + hi) / 2
        if f(mid) < target:
            lo = mid
        else:
            hi = mid
    return hi


def fit_flow(anchors, fits, churn, conversion=1.0):
    """Подбирает опоры None по очереди, каждую под свою цель по базе."""
    a = dict(anchors)
    for anchor_m, target_m, target in fits:
        later = [k for k, v in a.items() if v is None and k != anchor_m]

        def base_at(v, anchor_m=anchor_m, target_m=target_m, later=later):
            trial = dict(a)
            trial[anchor_m] = v
            for k in later:
                trial[k] = v
            adds = whole(x * conversion for x in flow(trial))
            return stock(adds, churn)[target_m]

        a[anchor_m] = solve(base_at, target)
    return a


def build(L, scale=1.0):
    r = {}
    N = MONTHS + 1

    # ── Труд ────────────────────────────────────────────────────────
    r["labor_anchors"] = fit_flow(L["labor_flow"], L["labor_fit"], L["labor_churn"])
    r["labor_adds"] = whole(x * scale for x in flow(r["labor_anchors"]))
    r["labor_base"] = stock(r["labor_adds"], L["labor_churn"])
    r["labor_arpa"] = flow(L["labor_arpa"])
    r["pilots"] = [float(L["pilots"].get(m, 0)) for m in range(N)]
    r["labor_rec"] = [r["labor_base"][m] * r["labor_arpa"][m] for m in range(N)]
    r["pilot_rev"] = [r["pilots"][m] * L["pilot_price"] for m in range(N)]

    # ── Личность ────────────────────────────────────────────────────
    r["ident_anchors"] = fit_flow(L["ident_visits"], L["ident_fit"], L["ident_churn"], L["ident_conversion"])
    r["visits"] = whole(x * scale for x in flow(r["ident_anchors"]))
    r["subs_adds"] = whole(v * L["ident_conversion"] for v in r["visits"])
    r["subs"] = stock(r["subs_adds"], L["ident_churn"])
    r["subs_rev"] = [s * L["ident_price"] for s in r["subs"]]
    r["brand_deals"] = whole(x * scale for x in flow(L["brand_flow"]))
    r["brand_rev"] = [d * L["brand_check"] for d in r["brand_deals"]]

    # ── Капитал ─────────────────────────────────────────────────────
    r["cap_anchors"] = fit_flow(L["cap_flow"], L["cap_fit"], L["cap_churn"])
    r["cap_adds"] = whole(x * scale for x in flow(r["cap_anchors"]))
    r["cap_base"] = stock(r["cap_adds"], L["cap_churn"])
    r["cap_arpa"] = flow(L["cap_arpa"])
    r["cap_rev"] = [r["cap_base"][m] * r["cap_arpa"][m] for m in range(N)]

    # ── Выручка ─────────────────────────────────────────────────────
    r["revenue"] = [r["labor_rec"][m] + r["pilot_rev"][m] + r["subs_rev"][m] + r["brand_rev"][m] + r["cap_rev"][m]
                    for m in range(N)]
    r["arr"] = [(r["labor_rec"][m] + r["subs_rev"][m] + r["cap_rev"][m]) * 12 for m in range(N)]

    # ── Себестоимость ───────────────────────────────────────────────
    r["cogs"] = [(r["labor_rec"][m] + r["pilot_rev"][m]) * L["cogs_labor"]
                 + r["subs_rev"][m] * L["cogs_subs"]
                 + r["brand_rev"][m] * L["cogs_brand"]
                 + r["cap_rev"][m] * L["cogs_cap"] for m in range(N)]
    r["gross"] = [r["revenue"][m] - r["cogs"][m] for m in range(N)]

    # ── Операционные ────────────────────────────────────────────────
    r["fte"] = whole(flow({0: L["fte"][1], **L["fte"]}))
    r["payroll"] = [r["fte"][m] * L["fte_cost_year"] / 12 for m in range(N)]
    r["hiring"] = [max(0.0, r["fte"][m] - r["fte"][m - 1]) * L["hire_cost"] if m else 0.0 for m in range(N)]
    r["commissions"] = [r["labor_adds"][m] * r["labor_arpa"][m] * 12 * L["commission"] for m in range(N)]
    r["acquisition"] = [r["labor_adds"][m] * L["cac_labor"] + r["cap_adds"][m] * L["cac_cap"]
                        + r["visits"][m] * L["cost_per_visit"] for m in range(N)]
    fixed = L["content_monthly"] + L["platform_monthly"] + L["legal_monthly"]
    r["fixed"] = [fixed if m else 0.0 for m in range(N)]
    r["ga"] = [r["payroll"][m] * L["ga_pct"] for m in range(N)]
    r["opex"] = [r["payroll"][m] + r["hiring"][m] + r["commissions"][m] + r["acquisition"][m]
                 + r["fixed"][m] + r["ga"][m] for m in range(N)]
    r["costs"] = [r["cogs"][m] + r["opex"][m] for m in range(N)]
    r["ebitda"] = [r["gross"][m] - r["opex"][m] for m in range(N)]

    # ── Деньги ──────────────────────────────────────────────────────
    cash = [0.0] * N
    cash[0] = L["raise_total"]
    for m in range(1, N):
        cash[m] = cash[m - 1] + r["ebitda"][m]
    r["cash"] = cash

    # ── Оценка как промежуточный результат ──────────────────────────
    def valuation(m):
        brand_t12 = sum(r["brand_rev"][max(1, m - 11):m + 1])
        return (r["labor_rec"][m] * 12 * L["mult_labor"] + r["cap_rev"][m] * 12 * L["mult_cap"]
                + r["subs_rev"][m] * 12 * L["mult_subs"] + brand_t12 * L["mult_brand"])
    r["valuation"] = [valuation(m) if m else 0.0 for m in range(N)]
    return r


def summary(r):
    """Итоги прогона: выход в плюс, дно кассы, годы."""
    N = MONTHS + 1
    be = next((m for m in range(1, N) if all(r["ebitda"][k] >= 0 for k in range(m, N))), None)
    low_m = min(range(1, N), key=lambda m: r["cash"][m])
    years = []
    for y in range(MONTHS // 12):
        ms = range(12 * y + 1, 12 * y + 13)
        years.append({k: sum(r[k][m] for m in ms) for k in
                      ("labor_rec", "pilot_rev", "subs_rev", "brand_rev", "cap_rev", "revenue", "cogs", "gross",
                       "payroll", "hiring", "commissions", "acquisition", "fixed", "ga", "opex", "ebitda")})
        years[-1]["cash_end"] = r["cash"][12 * y + 12]
    return {"breakeven": be, "low_m": low_m, "low_cash": r["cash"][low_m], "years": years}


