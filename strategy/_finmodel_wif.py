def curve(checkpoints, months=MONTHS, start_month=1, start_value=0.0):
    """Траектория через контрольные точки: экспонента между ними, ноль до старта.

    Экспонента, а не прямая: база клиентов растёт мультипликативно, и прямая
    завышала бы ранние месяцы, где на деле ещё ничего нет.
    """
    pts = sorted(checkpoints.items())
    out = [0.0] * (months + 1)
    prev_m, prev_v = start_month - 1, start_value
    for m, v in pts:
        span = m - prev_m
        for i in range(1, span + 1):
            if prev_v <= 0:
                # от нуля экспоненты нет — линейный выход на первую точку
                out[prev_m + i] = v * i / span
            else:
                out[prev_m + i] = prev_v * (v / prev_v) ** (i / span)
        prev_m, prev_v = m, v
    for m in range(prev_m + 1, months + 1):
        out[m] = prev_v
    for m in range(1, min(start_month, months + 1)):
        out[m] = 0.0
    return out


def gross_adds(actives, churn):
    """Сколько новых клиентов нужно в месяц, чтобы база шла по траектории."""
    adds = [0.0] * (len(actives))
    for m in range(1, len(actives)):
        adds[m] = max(0.0, actives[m] - actives[m - 1] * (1 - churn))
    return adds


def ramp(start_value, end_value, start_month, end_month, months=MONTHS):
    """Линейный выход показателя с start_month по end_month."""
    out = [0.0] * (months + 1)
    for m in range(1, months + 1):
        if m < start_month:
            out[m] = 0.0
        elif m >= end_month:
            out[m] = end_value
        else:
            k = (m - start_month) / (end_month - start_month)
            out[m] = start_value + (end_value - start_value) * k
    return out


def monthly_costs(stages, months=MONTHS):
    """Расход по месяцам: внутри этапа линейный рост, сумма равна бюджету этапа."""
    out = [0.0] * (months + 1)
    prev_end = None
    for first, last, total in stages:
        n = last - first + 1
        if prev_end is None:
            # первый этап: старт на 65% от среднего, дальше рост
            avg = total / n
            start = avg * 0.65
        else:
            start = prev_end
        end = 2 * total / n - start
        for i, m in enumerate(range(first, last + 1)):
            out[m] = start + (end - start) * (i / max(1, n - 1))
        prev_end = end
    return out


def build(levers, scale):
    L = levers
    r = {}

    def scaled(cp):
        return {m: v * scale for m, v in cp.items()}

    # ── Труд ────────────────────────────────────────────────────────
    r["labor_actives"] = curve(scaled(L["labor_checkpoints"]), start_month=6)
    r["labor_adds"] = gross_adds(r["labor_actives"], L["labor_churn"])
    r["labor_arpa"] = ramp(L["labor_arpa_start"], L["labor_arpa_end"], 6, MONTHS)
    r["labor_rev"] = [r["labor_actives"][m] * r["labor_arpa"][m] for m in range(MONTHS + 1)]
    for m, n in L["pilots"].items():
        r["labor_rev"][m] += n * L["pilot_price"]

    # ── Личность: подписка ──────────────────────────────────────────
    r["ident_subs"] = curve(scaled(L["ident_checkpoints"]), start_month=L["ident_start_month"])
    r["ident_adds"] = gross_adds(r["ident_subs"], L["ident_churn"])
    r["ident_visits"] = [a / L["ident_conversion"] for a in r["ident_adds"]]
    r["ident_rev"] = [s * L["ident_price"] for s in r["ident_subs"]]

    # ── Личность: бренды ────────────────────────────────────────────
    r["brand_deals"] = curve(scaled(L["brand_checkpoints"]), start_month=3)
    r["brand_rev"] = [d * L["brand_check"] for d in r["brand_deals"]]

    # ── Капитал ─────────────────────────────────────────────────────
    r["cap_actives"] = curve(scaled(L["cap_checkpoints"]), start_month=3)
    r["cap_adds"] = gross_adds(r["cap_actives"], L["cap_churn"])
    r["cap_arpa"] = ramp(L["cap_arpa_start"], L["cap_arpa_end"], 3, MONTHS)
    r["cap_rev"] = [r["cap_actives"][m] * r["cap_arpa"][m] for m in range(MONTHS + 1)]

    # ── Итог ────────────────────────────────────────────────────────
    r["revenue"] = [r["labor_rev"][m] + r["ident_rev"][m] + r["brand_rev"][m] + r["cap_rev"][m]
                    for m in range(MONTHS + 1)]

    r["fte"] = curve(L["fte_checkpoints"], start_month=1)
    fte_month = L["fte_cost_year"] / 12
    r["payroll"] = [r["fte"][m] * fte_month for m in range(MONTHS + 1)]
    r["costs"] = monthly_costs(L["stages"])
    r["other"] = [r["costs"][m] - r["payroll"][m] for m in range(MONTHS + 1)]

    r["net"] = [r["revenue"][m] - r["costs"][m] for m in range(MONTHS + 1)]
    cash = [0.0] * (MONTHS + 1)
    cash[0] = L["raise_total"]
    for m in range(1, MONTHS + 1):
        cash[m] = cash[m - 1] + r["net"][m]
    r["cash"] = cash

    r["arr"] = [(r["labor_rev"][m] + r["ident_rev"][m] + r["cap_rev"][m]) * 12
                for m in range(MONTHS + 1)]
    return r


def fmt_money(x, unit="млн"):
    if unit == "млн":
        return f"{x / 1e6:,.1f}".replace(",", " ").replace(".", ",")
    return f"{x / 1e3:,.0f}".replace(",", " ")


def dec(x, digits=1):
    """Число с запятой в дробной части — так пишут по-русски."""
    return f"{x:.{digits}f}".replace(".", ",")


def fmt_int(x):
    return f"{round(x):,}".replace(",", " ")


